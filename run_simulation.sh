#!/bin/bash
# ==============================================================================
# 지구-화성 DTN 시뮬레이션 통합 실행 스크립트
#
#   전체 흐름:
#     1) 실행 중인 CORE 세션(space_network.imn) 확인
#     2) configure_42.py   : 42 시뮬레이터 입력파일 생성
#     3) start_ion_nodes.sh: 4개 CORE 노드에 ION-DTN 기동
#     4) 42 시뮬레이터      : TCP 서버(4242)로 위치 상태 송출 (백그라운드)
#     5) bridging.py       : 42에 TCP 클라이언트로 접속 → 거리/가시성 계산 후
#                            tc/ionadmin 실시간 반영 (백그라운드)
#     6) Ctrl+C 시 4)5) 종료 및 ION 정리
#
#   * 42(Inp_IPC.txt: TX/SERVER)를 먼저 띄워 소켓을 연 뒤 브릿지(TCP 클라이언트)가
#     접속합니다. 브릿지는 접속 실패 시 자동 재시도하므로 순서에 민감하지 않습니다.
#
#   사용법:
#     ./run_simulation.sh
# ==============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# ------------------------------------------------------------------------------
# 환경 설정 (필요에 맞게 수정)
# ------------------------------------------------------------------------------
SIM42_DIR="/root/42"            # 42 시뮬레이터 설치 경로 (setup.sh 기준)
SIM42_BIN="$SIM42_DIR/42"       # 42 실행 파일
LOG_DIR="/tmp/em_sim_logs"      # 로그 출력 디렉터리

BRIDGE_PID=""
SIM42_PID=""

mkdir -p "$LOG_DIR"

# ------------------------------------------------------------------------------
# 종료 처리: 백그라운드 프로세스 정리 + ION 정지
# ------------------------------------------------------------------------------
cleanup() {
    echo ""
    echo "==================================================================="
    echo "[종료] 시뮬레이션을 정리합니다..."
    echo "==================================================================="

    if [ -n "$SIM42_PID" ] && kill -0 "$SIM42_PID" 2>/dev/null; then
        echo "  -> 42 시뮬레이터 종료 (PID $SIM42_PID)"
        kill "$SIM42_PID" 2>/dev/null || true
    fi

    if [ -n "$BRIDGE_PID" ] && kill -0 "$BRIDGE_PID" 2>/dev/null; then
        echo "  -> 브릿지 종료 (PID $BRIDGE_PID)"
        kill "$BRIDGE_PID" 2>/dev/null || true
    fi

    echo "  -> ION 노드 정지"
    bash "$SCRIPT_DIR/start_ion_nodes.sh" stop || true

    echo "[종료] 완료. 로그: $LOG_DIR"
    exit 0
}
trap cleanup INT TERM

# ------------------------------------------------------------------------------
# 1) CORE 세션 확인
# ------------------------------------------------------------------------------
echo "[1/5] CORE 세션 확인..."
SESSION_DIR=$(ls -d /tmp/pycore.* 2>/dev/null | head -n1)
if [ -z "$SESSION_DIR" ]; then
    echo "ERROR: 실행 중인 CORE 세션(/tmp/pycore.*)이 없습니다." >&2
    echo "       먼저 CORE에서 space_network.imn 토폴로지를 실행하세요." >&2
    exit 1
fi
echo "      CORE 세션: $SESSION_DIR"

# ------------------------------------------------------------------------------
# 2) 42 입력파일 생성
# ------------------------------------------------------------------------------
echo "[2/5] 42 시뮬레이터 입력파일 생성 (configure_42.py)..."
python3 "$SCRIPT_DIR/configure_42.py"

# ------------------------------------------------------------------------------
# 3) ION 노드 기동
# ------------------------------------------------------------------------------
echo "[3/5] ION-DTN 4개 노드 기동 (start_ion_nodes.sh)..."
bash "$SCRIPT_DIR/start_ion_nodes.sh" start

# ------------------------------------------------------------------------------
# 4) 42 시뮬레이터 기동 (TCP 서버 오픈) — 백그라운드
# ------------------------------------------------------------------------------
echo "[4/5] 42 시뮬레이터 기동..."
if [ ! -x "$SIM42_BIN" ]; then
    echo "ERROR: 42 실행파일을 찾을 수 없습니다: $SIM42_BIN" >&2
    echo "       setup.sh 로 42를 설치했는지, SIM42_DIR 경로가 맞는지 확인하세요." >&2
    cleanup
fi
# 42는 InOut/ 상대경로를 참조하므로 설치 디렉터리에서 실행
( cd "$SIM42_DIR" && "$SIM42_BIN" ) > "$LOG_DIR/sim42.log" 2>&1 &
SIM42_PID=$!
sleep 1
if ! kill -0 "$SIM42_PID" 2>/dev/null; then
    echo "ERROR: 42 시뮬레이터가 기동에 실패했습니다. 로그 확인: $LOG_DIR/sim42.log" >&2
    cat "$LOG_DIR/sim42.log" >&2
    cleanup
fi
echo "      42 PID: $SIM42_PID (로그: $LOG_DIR/sim42.log)"

# ------------------------------------------------------------------------------
# 5) 브릿지 기동 (42에 TCP 클라이언트로 접속) — 백그라운드
# ------------------------------------------------------------------------------
echo "[5/5] 브릿지 기동 (bridging.py) — 42에 TCP 접속..."
python3 "$SCRIPT_DIR/bridging.py" > "$LOG_DIR/bridge.log" 2>&1 &
BRIDGE_PID=$!
sleep 1
if ! kill -0 "$BRIDGE_PID" 2>/dev/null; then
    echo "ERROR: 브릿지가 기동에 실패했습니다. 로그 확인: $LOG_DIR/bridge.log" >&2
    cat "$LOG_DIR/bridge.log" >&2
    cleanup
fi
echo "      브릿지 PID: $BRIDGE_PID (로그: $LOG_DIR/bridge.log)"

# ------------------------------------------------------------------------------
# 실행 상태 유지 + 브릿지 로그 실시간 출력
# ------------------------------------------------------------------------------
echo ""
echo "==================================================================="
echo " 시뮬레이션 실행 중. 종료하려면 Ctrl+C 를 누르세요."
echo " - 브릿지 로그: $LOG_DIR/bridge.log"
echo " - 42 로그:     $LOG_DIR/sim42.log"
echo "==================================================================="
echo ""
echo "[브릿지 실시간 출력]"
tail -f "$LOG_DIR/bridge.log" &
TAIL_PID=$!

# 두 백그라운드 프로세스 중 하나라도 죽으면 정리
while kill -0 "$BRIDGE_PID" 2>/dev/null && kill -0 "$SIM42_PID" 2>/dev/null; do
    sleep 2
done

echo ""
echo "WARNING: 백그라운드 프로세스 중 하나가 종료되었습니다. 정리를 시작합니다." >&2
kill "$TAIL_PID" 2>/dev/null || true
cleanup